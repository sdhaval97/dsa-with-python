# printing a square
n = int(input("Enter number of rows: "))
for i in range(n):
    for j in range(n):
        print("*", end=" ")
    print()
        
# printing a rectangle
k = int(input("Enter the number of rows: "))
l = int(input("Enter the number of rows: "))
for i in range(k):
    for j in range(l):
        print("*", end=" ")
    print()